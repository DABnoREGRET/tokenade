//! YouTube: the video id, and the transcript reached through a Piped or
//! Invidious instance.
//!
//! Captions are the only part of a video an agent can read, and neither the
//! watch page nor the official API hands them over without a key.

use super::*;

/// Piped `/streams` endpoint for a video.
pub fn piped_streams_url(instance: &str, video_id: &str) -> String {
    format!("{}/streams/{video_id}", instance.trim_end_matches('/'))
}

/// From a Piped `/streams` JSON, pick the English subtitle track (manual
/// over auto) and return its (already absolute) caption url.
pub fn pick_en_piped_caption_url(streams_json: &str) -> Option<String> {
    let v: serde_json::Value = serde_json::from_str(streams_json).ok()?;
    let subs = v.get("subtitles")?.as_array()?;
    let en: Vec<&serde_json::Value> = subs
        .iter()
        .filter(|s| {
            s.get("code")
                .and_then(|c| c.as_str())
                .is_some_and(|c| c.starts_with("en"))
        })
        .collect();
    let pick = en
        .iter()
        .find(|s| {
            !s.get("autoGenerated")
                .and_then(|a| a.as_bool())
                .unwrap_or(false)
        })
        .or_else(|| en.first())?;
    pick.get("url").and_then(|u| u.as_str()).map(str::to_string)
}

/// Parse a YouTube `timedtext` XML caption (`<text start=…>line</text>`)
/// into plain transcript text. Piped subtitle urls sometimes serve this XML
/// form rather than VTT. `None` if it isn't timedtext XML.
pub fn timedtext_xml_to_transcript(xml: &str) -> Option<String> {
    if !xml.contains("<text") {
        return None;
    }
    let text_re = re(r"(?s)<text[^>]*>(.*?)</text>");
    let tag = re(r"<[^>]*>");
    let mut lines: Vec<String> = Vec::new();
    for c in text_re.captures_iter(xml) {
        let inner = tag.replace_all(c.get(1).unwrap().as_str(), "");
        let clean = crate::web::decode_entities(inner.trim());
        if !clean.is_empty() && lines.last().map(|p| p != &clean).unwrap_or(true) {
            lines.push(clean);
        }
    }
    (!lines.is_empty()).then(|| lines.join(" "))
}

/// Video id from a `watch?v=…` / `youtu.be/…` / `shorts/…` URL.
pub fn youtube_video_id(url: &str) -> Option<String> {
    let (_, path) = host_path(url)?;
    re(r"[?&]v=([A-Za-z0-9_-]{11})")
        .captures(&path)
        .or_else(|| re(r"/(?:shorts|embed)/([A-Za-z0-9_-]{11})").captures(&path))
        .or_else(|| re(r"^/([A-Za-z0-9_-]{11})").captures(&path))
        .map(|c| c[1].to_string())
}

/// Invidious caption-list endpoint for a video on `instance`.
pub fn invidious_caption_list_url(instance: &str, video_id: &str) -> String {
    format!(
        "{}/api/v1/captions/{video_id}",
        instance.trim_end_matches('/')
    )
}

pub(super) fn youtube_watch_plan(path: &str) -> Option<Plan> {
    let id = re(r"[?&]v=([A-Za-z0-9_-]{11})")
        .captures(path)
        .map(|c| c[1].to_string())
        .or_else(|| {
            re(r"^/shorts/([A-Za-z0-9_-]{11})")
                .captures(path)
                .map(|c| c[1].to_string())
        })?;
    Some(Plan::get(
        format!("https://www.youtube.com/watch?v={id}"),
        Kind::YouTube,
        "youtube",
    ))
}

pub(super) fn youtu_be_plan(path: &str) -> Option<Plan> {
    let id = re(r"^/([A-Za-z0-9_-]{11})").captures(path)?[1].to_string();
    Some(Plan::get(
        format!("https://www.youtube.com/watch?v={id}"),
        Kind::YouTube,
        "youtube",
    ))
}

