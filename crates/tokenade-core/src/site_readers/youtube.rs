/// From an Invidious caption-list JSON, pick the English track (manual over
/// auto-generated) and return its ABSOLUTE url on `instance`. `None` if the
/// list has no English track or isn't the expected shape.
pub fn pick_en_caption_url(list_json: &str, instance: &str) -> Option<String> {
    let v: serde_json::Value = serde_json::from_str(list_json).ok()?;
    let caps = v.get("captions")?.as_array()?;
    let en: Vec<&serde_json::Value> = caps
        .iter()
        .filter(|c| {
            c.get("languageCode")
                .and_then(|l| l.as_str())
                .is_some_and(|l| l.starts_with("en"))
        })
        .collect();
    // Manual caption (label without "auto-generated") wins over ASR.
    let pick = en
        .iter()
        .find(|c| {
            !c.get("label")
                .and_then(|l| l.as_str())
                .unwrap_or("")
                .contains("auto-generated")
        })
        .or_else(|| en.first())?;
    let rel = pick.get("url").and_then(|u| u.as_str())?;
    if rel.starts_with("http") {
        Some(rel.to_string())
    } else {
        Some(format!("{}{rel}", instance.trim_end_matches('/')))
    }
}

/// Clean a WebVTT caption file into plain transcript text: drop the header,
/// cue timings, cue ids and inline tags, and collapse the consecutive
/// duplicate lines that rolling (auto-generated) captions emit. `None` if
/// the body isn't VTT (an anti-bot HTML page slipped through).
pub fn vtt_to_transcript(vtt: &str) -> Option<String> {
    if !vtt.trim_start().starts_with("WEBVTT") && !vtt.contains("-->") {
        return None;
    }
    let tag = re(r"<[^>]*>");
    let mut lines: Vec<String> = Vec::new();
    for raw in vtt.lines() {
        let l = raw.trim();
        if l.is_empty()
            || l.starts_with("WEBVTT")
            || l.starts_with("Kind:")
            || l.starts_with("Language:")
            || l.starts_with("NOTE")
            || l.contains("-->")
            || l.chars().all(|c| c.is_ascii_digit())
        {
            continue;
        }
        let clean = tag.replace_all(l, "").trim().to_string();
        let clean = crate::web::decode_entities(&clean);
        if clean.is_empty() {
            continue;
        }
        // Rolling captions repeat the previous line as they scroll; skip an
        // exact consecutive duplicate.
        if lines.last().map(|p| p == &clean).unwrap_or(false) {
            continue;
        }
        lines.push(clean);
    }
    if lines.is_empty() {
        return None;
    }
    Some(lines.join(" "))
}

/// Render a YouTube watch page: title, channel, stats + full description
/// mined from the embedded `ytInitialPlayerResponse`.
pub(crate) fn youtube_watch(html: &str) -> Option<String> {
    let raw = extract_js_object(html, "ytInitialPlayerResponse")?;
    let pr: serde_json::Value = serde_json::from_str(raw).ok()?;
    let vd = pr.get("videoDetails")?;
    let title = vd.get("title").and_then(|t| t.as_str())?;
    let mut out = format!("# {title}\n");
    let mut meta: Vec<String> = Vec::new();
    if let Some(a) = vd.get("author").and_then(|a| a.as_str()) {
        meta.push(a.to_string());
    }
    if let Some(v) = vd.get("viewCount").and_then(|v| v.as_str()) {
        meta.push(format!("{v} views"));
    }
    if let Some(s) = vd
        .get("lengthSeconds")
        .and_then(|s| s.as_str())
        .and_then(|s| s.parse::<u64>().ok())
    {
        meta.push(format!("{}m{:02}s", s / 60, s % 60));
    }
    if !meta.is_empty() {
        out.push_str(&format!("> {} — youtube\n", meta.join(" • ")));
    }
    // Publish date lives in the microformat, not videoDetails.
    if let Some(d) = pr
        .pointer("/microformat/playerMicroformatRenderer/publishDate")
        .and_then(|d| d.as_str())
    {
        out.push_str(&format!("> published {d}\n"));
    }
    let desc = vd
        .get("shortDescription")
        .and_then(|d| d.as_str())
        .unwrap_or_default();
    if !desc.trim().is_empty() {
        out.push_str(&format!("\n## Description\n\n{}\n", desc.trim()));
    }
    // Honest note: transcript is not HTTP-only reachable (PO-token wall).
    if pr.pointer("/captions").is_some() {
        out.push_str(
            "\n(Captions exist but the transcript needs the YouTube player; \
             not fetched. The description above is the readable content.)\n",
        );
    }
    Some(out.trim_end().to_string())
}
