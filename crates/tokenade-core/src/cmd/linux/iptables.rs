//! `iptables -L` / `iptables-save` / `nft list ruleset`.
//!
//! ```text
//! Chain INPUT (policy ACCEPT)
//! target     prot opt source               destination
//! ACCEPT     all  --  anywhere             anywhere             state RELATED,ESTABLISHED
//! ACCEPT     tcp  --  anywhere             anywhere             tcp dpt:ssh
//! REJECT     all  --  anywhere             anywhere             reject-with icmp-host-prohibited
//!
//! Chain FORWARD (policy ACCEPT)
//! target     prot opt source               destination
//! ...
//! ```
//!
//! Compaction: keep chain headers, drop empty chains (no rules).

use std::fmt::Write;

pub fn detect(text: &str) -> bool {
    text.contains("Chain INPUT") && text.contains("target")
        || text.starts_with("# Generated by")
        || text.contains("Chain FORWARD") && text.contains("target")
}

crate::archetypes::detect_gated_try_compact!();

pub fn compact(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut current_chain_buf: Vec<String> = Vec::new();
    let mut has_rules_in_chain = false;
    let mut elided_empty = 0usize;
    let flush =
        |buf: &mut Vec<String>, has_rules: bool, out: &mut String, elided: &mut usize| {
            if buf.is_empty() {
                return;
            }
            if has_rules {
                for l in buf.iter() {
                    out.push_str(l);
                    out.push('\n');
                }
                out.push('\n');
            } else {
                *elided += 1;
            }
            buf.clear();
        };
    for line in text.lines() {
        if line.starts_with("Chain ") {
            flush(&mut current_chain_buf, has_rules_in_chain, &mut out, &mut elided_empty);
            has_rules_in_chain = false;
            current_chain_buf.push(line.to_string());
            continue;
        }
        if current_chain_buf.is_empty() {
            out.push_str(line);
            out.push('\n');
            continue;
        }
        if line.starts_with("target") || line.trim().is_empty() {
            current_chain_buf.push(line.to_string());
            continue;
        }
        // Non-header data line — chain has at least one rule.
        has_rules_in_chain = true;
        current_chain_buf.push(line.to_string());
    }
    flush(&mut current_chain_buf, has_rules_in_chain, &mut out, &mut elided_empty);
    if elided_empty > 0 {
        let _ = writeln!(out, "  [elided: {elided_empty} empty chain(s)]");
    }
    out.trim_end().to_string()
}

pub fn compact_with_savings(text: &str) -> (String, crate::Savings) {
    crate::archetypes::savings_of(text, compact)
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "Chain INPUT (policy ACCEPT)\ntarget     prot opt source               destination\nACCEPT     all  --  anywhere             anywhere\n\nChain FORWARD (policy ACCEPT)\ntarget     prot opt source               destination\n\nChain OUTPUT (policy ACCEPT)\ntarget     prot opt source               destination\n";

    #[test]
    fn detects_iptables_list() {
        assert!(detect(SAMPLE));
    }

    #[test]
    fn drops_empty_chains() {
        let out = compact(SAMPLE);
        assert!(out.contains("Chain INPUT"));
        assert!(!out.contains("Chain FORWARD"));
        assert!(out.contains("2 empty chain"));
    }

    #[test]
    fn rejects_random() {
        assert!(!detect("hello world"));
    }
}
