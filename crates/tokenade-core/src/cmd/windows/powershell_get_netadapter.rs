//! `powershell_get_netadapter` — powershell get netadapter.
const HEAD: usize = 60;


pub fn detect(text: &str) -> bool {
    text.contains("MacAddress") || text.contains("LinkSpeed") || text.contains("InterfaceDescription")
}

pub fn try_compact(text: &str) -> Option<String> {
    if !detect(text) { return None; }
    crate::table_fold::fold_table(text, HEAD, "powershell-get-netadapter", "adapter(s)")
}

crate::archetypes::cmd_entry_points!(crate::archetypes::passthrough);

#[cfg(test)]
mod tests {
    use super::*;
    fn make_table(n: usize) -> String {
        let hdr = "Name   InterfaceDescription   ifIndex   Status   MacAddress   LinkSpeed\n";
        let rows: String = (0..n).map(|i| format!("item{i}  col2  col3  col4\n")).collect();
        format!("{hdr}{rows}")
    }
    #[test] fn detector_rejects_empty() { assert!(!detect("")); }
    #[test] fn detector_accepts_header() { assert!(detect("Name   InterfaceDescription   ifIndex   Status   MacAddress   LinkSpeed")); }
    #[test] fn short_table_passes_through() { assert!(try_compact(&make_table(3)).is_none()); }
    #[test] fn long_table_folds() {
        let out = try_compact(&make_table(65)).unwrap();
        assert!(out.contains("[tokenade:powershell-get-netadapter]"));
        assert!(out.contains("(+5 more)"));
    }
    #[test] fn header_preserved() {
        let out = try_compact(&make_table(65)).unwrap();
        assert!(out.contains("Name"));
        assert!(out.contains("Status"));
    }
}
