//! `powershell_get_partition` — powershell get partition.
const HEAD: usize = 60;


pub fn detect(text: &str) -> bool {
    text.contains("PartitionNumber") || text.contains("DriveLetter") && text.contains("Size")
}

pub fn try_compact(text: &str) -> Option<String> {
    if !detect(text) { return None; }
    crate::table_fold::fold_table(text, HEAD, "powershell-get-partition", "partition(s)")
}

crate::archetypes::cmd_entry_points!(crate::archetypes::passthrough);

#[cfg(test)]
mod tests {
    use super::*;
    fn make_table(n: usize) -> String {
        let hdr = "DiskNumber   PartitionNumber   DriveLetter   Offset   Size   Type\n";
        let rows: String = (0..n).map(|i| format!("item{i}  col2  col3  col4\n")).collect();
        format!("{hdr}{rows}")
    }
    #[test] fn detector_rejects_empty() { assert!(!detect("")); }
    #[test] fn detector_accepts_header() { assert!(detect("DiskNumber   PartitionNumber   DriveLetter   Offset   Size   Type")); }
    #[test] fn short_table_passes_through() { assert!(try_compact(&make_table(3)).is_none()); }
    #[test] fn long_table_folds() {
        let out = try_compact(&make_table(65)).unwrap();
        assert!(out.contains("[tokenade:powershell-get-partition]"));
        assert!(out.contains("(+5 more)"));
    }
    #[test] fn header_preserved() {
        let out = try_compact(&make_table(65)).unwrap();
        assert!(out.contains("DiskNumber"));
        assert!(out.contains("DriveLetter"));
    }
}
