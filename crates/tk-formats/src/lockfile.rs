    #[test]
    fn go_sum_dedups_pairs() {
        let t = "github.com/a/b v1.0.0 h1:xxx=\ngithub.com/a/b v1.0.0/go.mod h1:yyy=\ngithub.com/c/d v2.0.0 h1:zzz=\ngithub.com/c/d v2.0.0/go.mod h1:www=\n";
        let out = compact(t);
        // Each module appears once after pair-dedup.
        assert!(out.contains("github.com/a/b v1.0.0"));
        assert!(out.contains("github.com/c/d v2.0.0"));
        assert!(out.contains("2 module-version(s)"));
        assert!(!out.contains("xxx="));
        assert!(!out.contains("/go.mod"));
    }

    #[test]
    fn yarn_lock_extracts_versions() {
        let t = "# yarn lockfile v1\n\n\"foo@^1.0.0\":\n  version \"1.2.3\"\n  resolved \"https://registry.npmjs.org/foo/-/foo-1.2.3.tgz#aaa\"\n  integrity sha512-aaaa==\n\n\"@scope/bar@^2.0.0\", \"@scope/bar@^2.0.1\":\n  version \"2.0.5\"\n  resolved \"...\"\n  integrity sha512-bbbb==\n";
        let out = compact(t);
        assert!(out.contains("foo 1.2.3"));
        assert!(out.contains("@scope/bar 2.0.5"));
        assert!(out.contains("2 package(s)"));
        assert!(!out.contains("integrity"));
        assert!(!out.contains("registry.npmjs.org"));
    }

    #[test]
    fn unknown_passes_through() {
        let t = "not a lockfile at all\njust prose\n";
        assert_eq!(compact(t), t);
    }

    #[test]
    fn savings_real_shape() {
        // Build a 50-package Cargo.lock-style input.
        let mut t =
            String::from("# This file is automatically @generated by Cargo.\nversion = 4\n\n");
        for i in 0..50 {
            let _ = write!(
                t,
                "[[package]]\nname = \"pkg{i}\"\nversion = \"{i}.0.0\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"{}\"\ndependencies = [\n \"dep_a\",\n \"dep_b\",\n \"dep_c\",\n]\n\n",
                "0123456789abcdef".repeat(4)
            );
        }
        let (out, sav) = compact_with_savings(&t);
        assert!(out.contains("50 package(s)"));
        assert!(sav.percent() > 75.0, "got {:?}", sav);
    }
